SNAPSHOT_FORMAT = 'hzb-process-snapshot'
CONTRACT_DIR = os.path.join(os.path.dirname(__file__), 'contracts')
EXPERIMENT_INFO = 'Experiment Info'
NOMAD_ID_TEMPLATE = '{lab}_{project}_{batch}_{sub_batch}_C-{number}'
MAX_REPORTED_ERRORS = 10
# modules whose code reads the Excel/snapshot field names into NOMAD
MAPPER_MODULES = (
    'baseclasses.helper.solar_cell_batch_mapping',
    'nomad_hysprint.parsers.file_parser.ink_recycling_mappers',
)


class RawHySprintProcessSnapshot(EntryData):
    processed_archive = Quantity(type=Entity, shape=['*'])
    snapshot_format = Quantity(
        type=str, description='Contract version of the snapshot, e.g. hzb-process-snapshot/v0.1.'
    )
    generator = Quantity(type=str, description='Tool that generated the snapshot.')
    generated_at = Quantity(type=str, description='When the snapshot was generated.')
    source_note = Quantity(type=str, description='Repository path of the batch note.')
    source_commit = Quantity(type=str, description='Commit of the batch note.')
    library = Quantity(type=str, description='Repository path of the process library.')
    library_commit = Quantity(type=str, description='Last commit that changed the process library.')
    provenance = Quantity(type=JSON, description='The complete provenance section of the snapshot.')
    unread_parameters = Quantity(
        type=str,
        shape=['*'],
        description=(
            'Field names in the snapshot that NOMAD does not read, with where they occur. '
            'Their values are not stored: usually a typo, or a field NOMAD has no place for yet.'
        ),
    )


def supported_versions():
    """Contract versions with a schema file, e.g. {'v0.1': '.../hzb-process-snapshot.v0.1.schema.json'}."""
    versions = {}
    for file_name in os.listdir(CONTRACT_DIR):
        match = re.match(rf'^{SNAPSHOT_FORMAT}\.(v[\w.]+)\.schema\.json$', file_name)
        if match:
            versions[match.group(1)] = os.path.join(CONTRACT_DIR, file_name)
    return versions


def load_contract(version):
    with open(supported_versions()[version], encoding='utf-8') as f:
        return json.load(f)


def _plain(value):
    """YAML turns unquoted dates into date objects; the contract expects strings."""
    if isinstance(value, dict):
        return {k: _plain(v) for k, v in value.items()}
    if isinstance(value, list):
        return [_plain(v) for v in value]
    if isinstance(value, datetime.date):
        return value.isoformat()
    return value


def load_snapshot(path):
    """Read a snapshot written as YAML or JSON."""
    with open(path, encoding='utf-8') as f:
        return _plain(yaml.safe_load(f))


def describe_error(error):
    """One line per contract violation; unknown field names get the closest known name."""
    where = '/'.join(str(p) for p in error.absolute_path) or '(top level)'
    if 'propertyNames' in error.schema_path and isinstance(error.instance, str):
        known = []
        for option in error.schema.get('anyOf', []):
            known += option.get('enum', [])
            if option.get('title'):
                known.append(option['title'])
        close = difflib.get_close_matches(error.instance, known, n=1, cutoff=0.6)
        hint = f' Did you mean "{close[0]}"?' if close else ''
        return f'{where}: unknown field "{error.instance}".{hint}'
    return f'{where}: {error.message}'


def validate_snapshot(snapshot):
    """Check a snapshot against its contract version and its internal references.

    Raises ValueError listing what is wrong; returns the contract version.
    """
    if not isinstance(snapshot, dict):
        raise ValueError('A process snapshot must be a mapping at the top level.')
    name, _, version = str(snapshot.get('format', '')).partition('/')
    versions = supported_versions()
    if name != SNAPSHOT_FORMAT or version not in versions:
        raise ValueError(
            f'Unsupported snapshot format "{snapshot.get("format")}". '
            f'Supported: {", ".join(f"{SNAPSHOT_FORMAT}/{v}" for v in sorted(versions))}.'
        )

    from jsonschema import Draft202012Validator

    validator = Draft202012Validator(
        load_contract(version), format_checker=Draft202012Validator.FORMAT_CHECKER
    )
    errors = [
        describe_error(error)
        for error in sorted(validator.iter_errors(snapshot), key=lambda e: list(map(str, e.absolute_path)))
    ]
    if not errors:
        errors = check_consistency(snapshot)
    if errors:
        shown = errors[:MAX_REPORTED_ERRORS]
        more = f' (and {len(errors) - len(shown)} more)' if len(errors) > len(shown) else ''
        raise ValueError(
            f'Process snapshot does not follow {SNAPSHOT_FORMAT}/{version}{more}: ' + '; '.join(shown)
        )
    return version


def nomad_id(experiment, sub_batch_id, number):
    return NOMAD_ID_TEMPLATE.format(
        lab=experiment['lab'],
        project=experiment['project'],
        batch=experiment['batch'],
        sub_batch=sub_batch_id,
        number=number,
    )


def check_consistency(snapshot):
    """What the JSON schema cannot express: references, uniqueness and IDs."""
    errors = []
    processes = snapshot['processes']
    experiment = snapshot['experiment']
    seen_numbers = {}
    seen_sub_batches = set()
    for index, sub_batch in enumerate(snapshot['sub_batches']):
        where = f'sub_batches/{index} ({sub_batch["id"]})'
        if sub_batch['id'] in seen_sub_batches:
            errors.append(f'{where}: sub-batch id "{sub_batch["id"]}" is used twice')
        seen_sub_batches.add(sub_batch['id'])

        for sample in sub_batch['samples']:
            number = sample['number']
            if number in seen_numbers:
                errors.append(
                    f'{where}: sample number {number} is also used in sub-batch {seen_numbers[number]}'
                )
            seen_numbers[number] = sub_batch['id']
            expected = nomad_id(experiment, sub_batch['id'], number)
            if sample.get('nomad_id') not in (None, expected):
                errors.append(
                    f'{where}: nomad_id "{sample["nomad_id"]}" of sample {number} should be "{expected}"'
                )

        positions = [step['position'] for step in sub_batch['steps']]
        if len(set(positions)) != len(positions):
            errors.append(f'{where}: step positions are not unique')
        step_names = [step['name'] for step in sub_batch['steps']]
        for sample in sub_batch['samples']:
            for step_name in sample.get('parameter_changes') or {}:
                if step_name not in step_names:
                    errors.append(
                        f'{where}: parameter_changes of sample {sample["number"]} refer to step '
                        f'"{step_name}", which is not a step of this sub-batch'
                    )
                elif step_names.count(step_name) > 1:
                    errors.append(
                        f'{where}: parameter_changes of sample {sample["number"]} refer to step '
                        f'"{step_name}", which occurs more than once'
                    )
        for step in sub_batch['steps']:
            for key in ('process', 'varied_from'):
                if key in step and step[key] not in processes:
                    errors.append(
                        f'{where}: step {step["position"]} "{step["name"]}" refers to {key} '
                        f'"{step[key]}", which is not in processes'
                    )
    return errors


@functools.cache
def mapped_field_names():
    """All field names the mapping code mentions: (exact names, patterns of f-strings).

    Read from the mappers' source, so it follows them when they change. An
    f-string such as f'Rotation speed {step}[rpm]' becomes a pattern whose
    placeholders match any text, including none.
    """
    exact, patterns = set(), []
    for module_name in MAPPER_MODULES:
        source = inspect.getsource(importlib.import_module(module_name))
        for node in ast.walk(ast.parse(source)):
            if isinstance(node, ast.Constant) and isinstance(node.value, str):
                exact.add(node.value)
            elif isinstance(node, ast.JoinedStr):
                pattern = ''.join(
                    re.escape(part.value) if isinstance(part, ast.Constant) else '.*?' for part in node.values
                )
                patterns.append(re.compile(f'^{pattern}$'))
    return frozenset(exact), tuple(patterns)


def unread_parameters(snapshot):
    """Field names of the snapshot that the mapping code never reads, with where they occur."""
    exact, patterns = mapped_field_names()
    fields = [('experiment properties', (snapshot['experiment'].get('properties') or {}))]
    fields += [
        (f'sub-batch {sub_batch["id"]} sample_properties', sub_batch.get('sample_properties') or {})
        for sub_batch in snapshot['sub_batches']
    ]
    fields += [(f'process {key}', process['parameters']) for key, process in snapshot['processes'].items()]
    for sub_batch in snapshot['sub_batches']:
        fields += [
            (
                f'sub-batch {sub_batch["id"]} step {step["position"]} parameter_changes',
                step['parameter_changes'],
            )
            for step in sub_batch['steps']
            if step.get('parameter_changes')
        ]
        fields += [
            (f'sample {sample["number"]} parameter_changes', changes)
            for sample in sub_batch['samples']
            for changes in (sample.get('parameter_changes') or {}).values()
        ]
    unread = {}
    for where, values in fields:
        for name in values:
            if name not in exact and not any(pattern.match(name) for pattern in patterns):
                if where not in unread.setdefault(name, []):
                    unread[name].append(where)
    return unread


def step_slot(step, method, version):
    """The process column a step belongs to; see 'steps' in the contract.

    v0.1: the run label, else the Excel section, else the step name.
    v0.2: the slot, split further by the run label.
    """
    if version != 'v0.1':
        key = ('slot', step['slot'], step.get('run') or '')
    elif step.get('run'):
        key = ('run', step['run'])
    elif step.get('excel_section'):
        key = ('excel_section', step['excel_section'])
    else:
        key = ('name', step['name'])
    return key + (method,)


def order_slots(sequences):
    """Order process columns so that every sub-batch's steps stay in order.

    ``sequences`` holds one list of (slot, position) per sub-batch. Columns are
    sorted topologically along the sub-batches' step order; ties, and cycles if
    sub-batches disagree, are resolved by the smallest step position.
    """
    first_position = {}
    successors = {}
    in_degree = {}
    for sequence in sequences:
        for slot, position in sequence:
            first_position[slot] = min(position, first_position.get(slot, position))
            successors.setdefault(slot, set())
            in_degree.setdefault(slot, 0)
        for (before, _), (after, _) in zip(sequence, sequence[1:]):
            if after not in successors[before]:
                successors[before].add(after)
                in_degree[after] += 1

    def rank(slot):
        return (first_position[slot], str(slot))

    ready = [(rank(s), s) for s, d in in_degree.items() if d == 0]
    heapq.heapify(ready)
    ordered = []
    while len(ordered) < len(in_degree):
        if not ready:  # cycle: continue with the earliest remaining column
            slot = min((s for s in in_degree if s not in ordered), key=rank)
            in_degree[slot] = 0
            heapq.heappush(ready, (rank(slot), slot))
        _, slot = heapq.heappop(ready)
        if slot in ordered:
            continue
        ordered.append(slot)
        for after in successors[slot]:
            in_degree[after] -= 1
            if in_degree[after] == 0:
                heapq.heappush(ready, (rank(after), after))
    return ordered


def section_number(section):
    return int(section.split(':', 1)[0])


def build_snapshot_dataframe(snapshot):
    """Convert a validated snapshot into the Excel experiment table.

    Each process column holds, per sample, the parameters of its step's process
    with the step's and the sample's parameter_changes applied, plus the process
    id (RECIPE_COLUMN), so two different processes never become one entry.
    """
    version = str(snapshot['format']).partition('/')[2]
    experiment = snapshot['experiment']
    processes = snapshot['processes']
    defaults = dict(experiment.get('properties') or {})
    if experiment.get('date'):
        defaults['Date'] = experiment['date']
    defaults.update(Project_Name=experiment['project'], Batch=experiment['batch'])

    sequences = []
    for sub_batch in snapshot['sub_batches']:
        steps = sorted(sub_batch['steps'], key=lambda s: s['position'])
        sequences.append(
            [
                (step_slot(step, processes[step['process']]['method'], version), step['position'])
                for step in steps
            ]
        )
    all_steps = [step for sub_batch in snapshot['sub_batches'] for step in sub_batch['steps']]
    if version == 'v0.1' and all(step.get('excel_section') for step in all_steps):
        section_of = {}
        for sub_batch, sequence in zip(snapshot['sub_batches'], sequences):
            steps = sorted(sub_batch['steps'], key=lambda s: s['position'])
            for step, (slot, _) in zip(steps, sequence):
                section_of[slot] = section_number(step['excel_section'])
        slots = sorted(order_slots(sequences), key=lambda s: section_of[s])
    else:
        slots = order_slots(sequences)
    headers = {slot: f'{index}: {slot[-1]}' for index, slot in enumerate(slots, start=1)}

    rows = []
    columns = {header: {} for header in headers.values()}
    for sub_batch, sequence in zip(snapshot['sub_batches'], sequences):
        cell_type = sub_batch['cell_type']
        description = [sub_batch.get('variation') or cell_type['display_name']]
        description += [sub_batch[key] for key in ('notes', 'lab_comment') if sub_batch.get(key)]
        steps = sorted(sub_batch['steps'], key=lambda s: s['position'])
        for sample in sub_batch['samples']:
            info = dict(defaults)
            info.update(Subbatch=sub_batch['id'], Sample=sample['number'])
            info['Nomad ID'] = nomad_id(experiment, sub_batch['id'], sample['number'])
            info.update(sub_batch.get('sample_properties') or {})
            info['Architecture'] = cell_type['display_name']
            info['Variation'] = '; '.join(description)
            row = {(EXPERIMENT_INFO, k): v for k, v in info.items()}
            sample_changes = sample.get('parameter_changes') or {}
            for step, (slot, _) in zip(steps, sequence):
                header = headers[slot]
                if any(key[0] == header for key in row):
                    raise ValueError(
                        f'Sub-batch {sub_batch["id"]}: several steps fall into the same process '
                        f'({slot[0]} "{slot[1]}"); give them different slots or "run" labels.'
                    )
                values = dict(processes[step['process']]['parameters'])
                values.update(step.get('parameter_changes') or {})
                values.update(sample_changes.get(step['name']) or {})
                values[RECIPE_COLUMN] = step['process']
                for name, value in values.items():
                    columns[header][name] = None
                    row[(header, name)] = value
            rows.append(row)

    info_columns = list(dict.fromkeys(k for row in rows for k in row if k[0] == EXPERIMENT_INFO))
    process_columns = [(header, name) for header in headers.values() for name in columns[header]]
    return pd.DataFrame(rows, columns=pd.MultiIndex.from_tuples(info_columns + process_columns), dtype=object)


class HySprintProcessSnapshotParser(MatchingParser):
    """Parses process snapshots (contract v0.1, v0.2) and batch notes with their process library."""

    def is_mainfile(
        self,
        filename: str,
        mime: str,
        buffer: bytes,
        decoded_buffer: str,
        compression: str = None,
    ):
        if not super().is_mainfile(filename, mime, buffer, decoded_buffer, compression):
            return False
        try:
            data = load_snapshot(filename)
            return str(data.get('format', '')).startswith(f'{SNAPSHOT_FORMAT}/') or is_batch_note(data)
        except Exception:
            return False

    def parse(self, mainfile: str, archive: EntryArchive, logger):
        snapshot = load_snapshot(mainfile)
        if is_batch_note(snapshot):
            snapshot = load_batch_note_snapshot(mainfile, archive, snapshot, logger)
        validate_snapshot(snapshot)

        df = build_snapshot_dataframe(snapshot)
        info = df[EXPERIMENT_INFO]
        experiment = snapshot['experiment']
        batch_id = f'{experiment["lab"]}_{experiment["project"]}_{experiment["batch"]}'
        refs = build_experiment_archives(df, archive, info['Nomad ID'].to_list(), batch_id)

        # one sub-batch entry per sub-batch of the snapshot
        upload_id = archive.metadata.upload_id
        for sub_batch, group in info.groupby('Subbatch', sort=False):
            subbatch_id, subbatch_entry = map_subbatch(
                group['Nomad ID'].to_list(), f'{batch_id}_{sub_batch}', upload_id, HySprint_Batch
            )
            subbatch_entry.description = group['Variation'].iloc[0]
            file_name = f'{subbatch_id}.archive.json'
            create_archive(subbatch_entry, archive, file_name)
            refs.append(get_reference(upload_id, file_name))

        provenance = snapshot['provenance']
        try:
            unread = unread_parameters(snapshot)
        except (OSError, TypeError, SyntaxError):  # mapper source not available
            unread = {}
        if unread:
            logger.warning('snapshot fields not read by NOMAD, their values are not stored', fields=unread)
        archive.data = RawHySprintProcessSnapshot(
            processed_archive=refs,
            snapshot_format=snapshot['format'],
            provenance=provenance,
            unread_parameters=[f'{name} ({", ".join(where)})' for name, where in unread.items()] or None,
            **{
                key: str(provenance[key])
                for key in RawHySprintProcessSnapshot.m_def.all_quantities
                if provenance.get(key) is not None
            },
        )
