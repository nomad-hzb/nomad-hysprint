"""Parser for HZB process snapshots.

A process snapshot (``format: hzb-process-snapshot/<version>``) describes one
experiment batch fully resolved: every sample, every process step in order and
every parameter value. It is generated by CI from a batch note and the process
library. Its structure is fixed by a versioned JSON schema, the uploader
contract, in ``contracts/`` (currently v0.2).

A batch can also be uploaded as its batch note plus process library; the
batch note is then merged into a snapshot first (``hysprint_batch_note``).

The snapshot is converted into the same two-level table as the HySprint
experiment Excel file, so all entries are created by the same code as for the
Excel file (``build_experiment_archives``).
"""

